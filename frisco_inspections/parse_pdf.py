"""Parse a Frisco inspection report PDF ("View Original Inspection PDF").

The PDF is generated by the portal (PDFKit) and has a fixed layout:

* Page 1 is an image of the Texas DSHS Food Establishment Inspection Report
  with values overlaid as text. Every value is drawn at the same position as
  a small bold field label (the labels are the template's field names), so a
  value is identified by the label it sits on. Demerit points are written
  next to the OUT box of each of the 47 numbered items.
* Pages 2+ list measured temperatures / sanitizer readings, a general
  comment, then one block per violation:

      2. Proper Cold Holding temperature(41°F/ 45°F)     <- bold
      Status: OUT
      Type: Corrected On Site / Repeat                   <- optional
      Comments: ...                                      <- may wrap
      Violation Code - *3-501.16(A)(2) - ...             <- may wrap

  Those pages repeat the page-1 header overlay in 14pt/22pt text, so only
  the 20pt body text is read.
"""

import re
import sys

import pdfplumber

LABEL_SIZE = 14
VALUE_SIZES = (22, 60)
BODY_SIZE = 20

# Page-1 header fields: (output key, label text, label x0, label top). Labels
# repeat ("Time In" is used for both time in and time out), so each field is
# pinned to where its label sits on the form. A label given as "A|B" accepts
# either text (the template has varied: "License Name" / "Establishment Name").
HEADER_FIELDS = [
    ("page_number", "pa", 1521, 152),
    ("page_count", "pa", 1583, 152),
    ("date", "Date", 74, 181),
    ("time_in", "Time In", 272, 181),
    ("time_out", "Time In", 475, 182),
    ("permit_number", "PR", 673, 179),
    ("permit_type", "PR", 1170, 179),
    ("risk_category", "Risk", 1340, 179),
    ("repeat_count", "R", 1347, 241),
    ("score", "score", 1499, 255),
    ("cos_count", "COS", 1347, 261),
    ("owner_name", "OWNERName", 605, 270),
    ("establishment_name", "License Name|Establishment Name", 66, 271),
    ("followup_required", "Followup", 1381, 302),
    ("street", "Physical address", 65, 327),
    ("city", "Physical address", 557, 327),
    ("zip", "Physical address", 826, 327),
    ("person_in_charge", "Inspector sign", 883, 1983),
    ("person_in_charge_title", "OWNERName", 1304, 2008),
    ("inspector", "Inspector sign", 882, 2036),
    ("inspector_email", "email", 1304, 2060),
]

# The item grid has two columns of OUT boxes. Points written in the left box
# (x ~ 63-80) belong to the item labelled at x ~ 778 on the same row; points
# in the middle box (x ~ 837-855) belong to the item labelled at x ~ 1622.
GRID_TOP, GRID_BOTTOM = 480, 1975
GRID_COLUMNS = [((40, 200), 778), ((800, 950), 1622)]


class ParseError(Exception):
    pass


def _size(c):
    return int(round(c["size"]))


def _is_bold(c):
    return "Bold" in c["fontname"]


def _words(page, size_pred, bold=None):
    sub = page.filter(
        lambda o: o.get("object_type") != "char"
        or (size_pred(_size(o)) and (bold is None or _is_bold(o) == bold))
    )
    return sub.extract_words(keep_blank_chars=True, x_tolerance=3, use_text_flow=True)


def parse_header(page):
    labels = _words(page, lambda s: s == LABEL_SIZE, bold=True)
    values = _words(page, lambda s: s in VALUE_SIZES, bold=False)

    slots = {}
    for key, text, x, top in HEADER_FIELDS:
        cands = [
            l for l in labels
            if l["text"].strip() in text.split("|") and abs(l["x0"] - x) < 40 and abs(l["top"] - top) < 25
        ]
        if cands:
            slots[key] = min(cands, key=lambda l: abs(l["x0"] - x) + abs(l["top"] - top))

    header = {k: None for k, *_ in HEADER_FIELDS}
    header["owner_name_truncated"] = header["establishment_name_truncated"] = False
    used = set()
    for key, label in slots.items():
        best = None
        for i, v in enumerate(values):
            dx, dy = v["x0"] - label["x0"], v["top"] - label["top"]
            # Values start at (or a few px right of) their label's x0 and
            # sit ~1px lower; the big 60pt score is offset further.
            limit_dx, limit_dy = (40, 20) if key == "score" else (40, 6)
            if -3 <= dx <= limit_dx and abs(dy) <= limit_dy and i not in used:
                if best is None or abs(dx) + abs(dy) < best[0]:
                    best = (abs(dx) + abs(dy), i)
        if best:
            used.add(best[1])
            raw = values[best[1]]["text"]
            header[key] = raw.strip()
            if key in ("owner_name", "establishment_name"):
                # The form cuts long values off; the cut leaves a trailing space.
                header[key + "_truncated"] = raw != raw.rstrip()

    unplaced = [
        v["text"] for i, v in enumerate(values)
        if i not in used and not (GRID_TOP <= v["top"] <= GRID_BOTTOM)
    ]
    header["_unplaced_values"] = unplaced
    return header, labels, values


def parse_points(labels, values):
    item_labels = []
    for l in labels:
        m = re.match(r"\s*(\d+)", l["text"])
        if m and GRID_TOP <= l["top"] <= GRID_BOTTOM:
            for _, label_x in GRID_COLUMNS:
                if abs(l["x0"] - label_x) < 15:
                    item_labels.append((label_x, l["top"], int(m.group(1))))
    points = {}
    stray = []
    for v in values:
        if not (GRID_TOP <= v["top"] <= GRID_BOTTOM):
            continue
        col = next((lx for (x0, x1), lx in GRID_COLUMNS if x0 <= v["x0"] <= x1), None)
        rows = [(abs(top - v["top"]), item) for lx, top, item in item_labels if lx == col]
        if col is None or not rows or min(rows)[0] > 20 or not v["text"].strip().isdigit():
            stray.append(v["text"])
            continue
        item = min(rows)[1]
        if item in points:
            raise ParseError(f"two point values for item {item}")
        points[item] = int(v["text"].strip())
    return points, stray


def _body_lines(pdf):
    """20pt body lines from pages 2+, each with a flag for all-bold text."""
    out = []
    for pno, page in enumerate(pdf.pages[1:], start=2):
        page = page.dedupe_chars()
        body = page.filter(
            lambda o: o.get("object_type") != "char" or _size(o) == BODY_SIZE
        )
        for line in body.extract_text_lines(return_chars=True, keep_blank_chars=True):
            text = line["text"].rstrip()
            if not text.strip():
                continue
            chars = [c for c in line["chars"] if c["text"].strip()]
            bold = bool(chars) and all(_is_bold(c) for c in chars)
            out.append({"page": pno, "text": text, "bold": bold})
    return out


