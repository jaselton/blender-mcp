def _is_known_title(item, title):
    known = KNOWN_TITLES.get(item)
    return bool(known) and title.strip()[:30].lower() == known[:30].lower()


MEASURE_RE = re.compile(
    r"^Item:\s*(?P<item>.*?)\s+Location:\s*(?P<location>.*?)\s+"
    r"Measurement:\s*(?P<value>.*?)\s+Temperature Type:\s*(?P<unit>.*)$"
)
HEADER_RE = re.compile(r"^(\d{1,2})\.\s+(.*)$")
FIELD_RE = re.compile(r"^(Status|Type|Comments|Correct By Date):\s?(.*)$")
CODE_RE = re.compile(r"^Violation Code\s*-\s*(.*)$")


def parse_body(lines):
    raw_measurements, general, violations, warnings = [], [], [], []
    section = None  # measurements | general | violation
    cur = None
    field = None

    for ln in lines:
        text, bold = ln["text"], ln["bold"]
        if bold and text.strip() == "Measured Observations":
            # Printed at the top of every page after the first; only the
            # first occurrence starts a section.
            if section is None:
                section = "measurements"
            continue
        if text.startswith("General Comment:"):
            # Bold label; the comment (regular weight) may start on the same line.
            section, field = "general", None
            rest = text[len("General Comment:"):].strip()
            if rest:
                general.append(rest)
            continue
        m = HEADER_RE.match(text)
        if m and (bold or _is_known_title(int(m.group(1)), m.group(2))):
            cur = {
                "item_number": int(m.group(1)),
                "item_title": m.group(2).strip(),
                "status": None,
                "type": None,
                "correct_by_date": None,
                "comments": [],
                "code_lines": [],
                "page": ln["page"],
            }
            violations.append(cur)
            section, field = "violation", "title"
            continue
        if section == "violation":
            fm = FIELD_RE.match(text)
            cm = CODE_RE.match(text)
            if fm:
                field = fm.group(1).lower().replace(" ", "_")
                val = fm.group(2).strip()
                if field == "comments":
                    cur["comments"].append(val)
                else:
                    cur[field] = val
            elif cm:
                field = "code"
                cur["code_lines"].append([cm.group(1).strip()])
            elif field == "title" and bold:
                cur["item_title"] += " " + text.strip()
            elif field == "comments":
                cur["comments"].append(text.strip())
            elif field == "code":
                cur["code_lines"][-1].append(text.strip())
            else:
                raise ParseError(f"unexpected line in violation {cur['item_number']}: {text!r}")
        elif section == "measurements":
            # Each reading starts with "Item:"; a long one wraps onto the
            # following line(s), so lines are joined until the next "Item:".
            if text.strip().startswith("Item:"):
                raw_measurements.append(text.strip())
            elif raw_measurements:
                raw_measurements[-1] += " " + text.strip()
            else:
                raise ParseError(f"unexpected measurement line: {text!r}")
        elif section == "general":
            general.append(text.strip())
        else:
            raise ParseError(f"text before any section: {text!r}")

    measurements = []
    for raw in raw_measurements:
        mm = MEASURE_RE.match(raw)
        if mm:
            measurements.append({k: v.strip() for k, v in mm.groupdict().items()})
        else:
            warnings.append(f"unparsed measurement: {raw!r}")
            measurements.append({"item": raw, "location": "", "value": "", "unit": ""})

    out = []
    for v in violations:
        codes = []
        for parts in v["code_lines"]:
            full = " ".join(p for p in parts if p)
            # "<code> - <rule text>"; codes contain hyphens but never " - ".
            code, _, desc = full.partition(" - ")
            code = code.strip()
            if code in ("", "-"):
                code = ""  # printed as "Violation Code -  -": no citation entered
            codes.append({"code": code, "code_text": desc.strip()})
        vtype = (v["type"] or "").strip()
        out.append({
            "item_number": v["item_number"],
            "item_title": v["item_title"],
            "status": (v["status"] or "").strip(),
            "type": vtype,
            "corrected_on_site": "Corrected On Site" in vtype,
            "repeat": "Repeat" in vtype,
            "comments": " ".join(c for c in v["comments"] if c).strip(),
            "correct_by_date": v["correct_by_date"] or None,
            "codes": codes,
            "page": v["page"],
        })
    return measurements, " ".join(general).strip(), out, warnings


def parse_pdf(path):
    with pdfplumber.open(path) as pdf:
        first = pdf.pages[0].dedupe_chars()
        header, labels, values = parse_header(first)
        points, stray = parse_points(labels, values)
        lines = _body_lines(pdf)
        measurements, general_comment, violations, body_warnings = parse_body(lines)
        n_pages = len(pdf.pages)
    unplaced = header.pop("_unplaced_values")
    return {
        "header": header,
        "points_by_item": {str(k): v for k, v in sorted(points.items())},
        "measurements": measurements,
        "general_comment": general_comment,
        "violations": violations,
        "pdf_pages": n_pages,
        "parse_warnings": (
            [f"unplaced header value: {u!r}" for u in unplaced]
            + [f"unplaced grid value: {s!r}" for s in stray]
            + body_warnings
        ),
    }


